"""Original polygon icons: generate the SVGs and dependency-free runtime header.

Source of truth for weapon_icons.h. Model silhouettes live in
model_silhouettes.py (outer contours + cut-outs, decomposed to convex pieces).
Every runtime component is convex for triangle-fan rendering. Pillow is
optional and only used for the review PNGs.
"""
from pathlib import Path

from model_silhouettes import ICONS as MODEL_ICONS, DISPLAY

ROOT = Path(__file__).resolve().parent

# Enum order is ABI for weapon_wheel_graphics.h callers: append only.
GENERIC = ["EmptyHand", "Pistol", "Revolver", "Smg", "Shotgun", "AssaultRifle"]
MODELS = ["M1911", "Cobra", "DesertEagle", "MicroUzi", "Ump45", "Mp7",
          "Defender", "SawnOff", "M1887", "Kalashnikov", "Carbine", "Striker"]
ORDER = GENERIC + MODELS
# Generic family fallbacks reuse a representative model silhouette (the
# first chunky generic set was rejected by the user).
ALIAS = {"Pistol": "M1911", "Revolver": "Cobra", "Smg": "MicroUzi",
         "Shotgun": "Defender", "AssaultRifle": "Carbine"}
FAMILY = {"EmptyHand": "EmptyHand", "Pistol": "Pistol", "Revolver": "Revolver", "Smg": "Smg",
          "Shotgun": "Shotgun", "AssaultRifle": "AssaultRifle",
          "M1911": "Pistol", "Cobra": "Revolver", "DesertEagle": "Pistol",
          "MicroUzi": "Smg", "Ump45": "Smg", "Mp7": "Smg",
          "Defender": "Shotgun", "SawnOff": "Shotgun", "M1887": "Shotgun",
          "Kalashnikov": "AssaultRifle", "Carbine": "AssaultRifle", "Striker": "AssaultRifle"}
# Darkness II carry class: pistols/SMGs/sawn-off are one-handed (dual
# wieldable), long guns two-handed. Presentation hint only, not equip proof.
TWO_HANDED = {"Shotgun", "AssaultRifle", "Defender", "M1887", "Kalashnikov", "Carbine", "Striker"}

# Budgets. A full 8-slot wheel draws 8 icons + the centre hand inside
# MaxVerticesPerWheel=4096 together with ~1.8k vertices of wheel chrome.
MAX_POLYGONS = 64
MAX_POINTS = 8
MAX_TRIANGLES = 80
MIN_TRIANGLE_AREA = 0.02   # icon units^2; keeps runtime triangles non-degenerate
INK_BOX = (3, 18, 97, 92)  # keeps every slot icon inside the wheel disc


def shape(name):
    return MODEL_ICONS[ALIAS.get(name, name)]


def validate():
    stats = {}
    for name in ORDER:
        polygons = shape(name)
        assert 1 <= len(polygons) <= MAX_POLYGONS, (name, len(polygons))
        tris = 0
        for poly in polygons:
            assert 3 <= len(poly) <= MAX_POINTS, (name, poly)
            assert all(INK_BOX[0] <= x <= INK_BOX[2] and INK_BOX[1] - 10 <= y <= INK_BOX[3] for x, y in poly), (name, poly)
            turns = []
            for i in range(len(poly)):
                a, b, c = poly[i-2], poly[i-1], poly[i]
                turns.append((b[0]-a[0])*(c[1]-b[1]) - (b[1]-a[1])*(c[0]-b[0]))
            assert all(t >= -1e-9 for t in turns) or all(t <= 1e-9 for t in turns), (name, poly, turns)
            for k in range(1, len(poly) - 1):
                a, b, c = poly[0], poly[k], poly[k+1]
                area = abs((b[0]-a[0])*(c[1]-a[1]) - (b[1]-a[1])*(c[0]-a[0])) * .5
                assert area >= MIN_TRIANGLE_AREA, (name, poly, area)
            tris += len(poly) - 2
        assert tris <= MAX_TRIANGLES, (name, tris)
        stats[name] = (len(polygons), tris)
    return stats


def fmt(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return s + (".0f" if "." not in s else "f")


def svg_path(polygons):
    return " ".join("M" + " L".join(f"{x:g},{y:g}" for x, y in poly) + " Z" for poly in polygons)


def write_header():
    h = ["// Generated by generate_icons.py; original art, no runtime asset I/O.",
         "#pragma once", "#include <cstddef>", "namespace d2vr_weapon_icons {",
         "// Append-only order. Generic families first, then concrete Darkness II models.",
         "enum class Icon { " + ", ".join(ORDER) + ", Count };",
         "struct Point { float x,y; };",
         "struct Polygon { const Point* points; std::size_t count; };",
         "struct Shape { const Polygon* polygons; std::size_t count; };",
         "// All polygons are convex in 0..100 coordinates, positive Y down, muzzle right.",
         "// Components may touch/overlap: draw icon ink opaque, or rasterize the union first."]
    for name in [n for n in ORDER if n not in ALIAS]:
        polygons = MODEL_ICONS[name]
        for i, poly in enumerate(polygons):
            h.append(f"inline constexpr Point k{name}{i}[] = {{" +
                     ",".join(f"{{{fmt(x)},{fmt(y)}}}" for x, y in poly) + "};")
        h.append(f"inline constexpr Polygon k{name}Polygons[] = {{" +
                 ",".join(f"{{k{name}{i},{len(p)}}}" for i, p in enumerate(polygons)) + "};")
        h.append(f"inline constexpr Shape k{name} = {{k{name}Polygons,{len(polygons)}}};")
    h += ["inline constexpr Shape Get(Icon icon) {", "    switch(icon) {"]
    for name in ORDER:
        h.append(f"    case Icon::{name}: return k{ALIAS.get(name, name)};")
    h += ["    default: break;", "    }", "    return kEmptyHand;", "}",
          "// Generic family of a model icon (families map to themselves).",
          "inline constexpr Icon Family(Icon icon) {", "    switch(icon) {"]
    for name in ORDER:
        h.append(f"    case Icon::{name}: return Icon::{FAMILY[name]};")
    h += ["    default: break;", "    }", "    return Icon::EmptyHand;", "}",
          "// Presentation hint: Darkness II carries this class in both hands (two-handed).",
          "inline constexpr bool TwoHanded(Icon icon) {", "    switch(icon) {"]
    for name in ORDER:
        if name in TWO_HANDED:
            h.append(f"    case Icon::{name}:")
    h += ["        return true;", "    default: return false;", "    }", "}",
          "inline constexpr const char* Name(Icon icon) {", "    switch(icon) {"]
    for name in ORDER:
        h.append(f'    case Icon::{name}: return "{DISPLAY.get(name, name)}";')
    h += ["    default: break;", "    }", '    return "";', "}",
          "} // namespace d2vr_weapon_icons", ""]
    (ROOT / "weapon_icons.h").write_text("\n".join(h), encoding="utf-8")


def write_svgs():
    for name in ORDER:
        polygons = shape(name)
        svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" fill="currentColor">',
               f'<title>{DISPLAY.get(name, name)} weapon selection icon</title>',
               f'<path d="{svg_path(polygons)}"/>', '</svg>']
        (ROOT / f"{name}.svg").write_text("\n".join(svg) + "\n", encoding="utf-8")
    cols, cell = 6, 160
    rows = (len(ORDER) + cols - 1) // cols
    w, hgt = cols * cell + 40, rows * cell + 70
    sheet = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{hgt}" viewBox="0 0 {w} {hgt}">',
             f'<rect width="{w}" height="{hgt}" fill="#111218"/>',
             '<text x="20" y="36" fill="#e9e7e2" font-family="sans-serif" font-size="18">'
             'DARKNESS II VR / WEAPON ICONS (generic fallbacks, then models)</text>']
    for i, name in enumerate(ORDER):
        x, y = 20 + (i % cols) * cell, 55 + (i // cols) * cell
        sheet += [f'<rect x="{x+4}" y="{y+4}" width="{cell-8}" height="{cell-8}" rx="14" fill="#1c1c25" stroke="#35343f"/>',
                  f'<g transform="translate({x+10} {y+4}) scale(1.4)" fill="#eee8dc"><path d="{svg_path(shape(name))}"/></g>',
                  f'<text x="{x+cell/2}" y="{y+cell-14}" fill="#c9c4bb" text-anchor="middle" '
                  f'font-family="sans-serif" font-size="13">{name}</text>']
    sheet.append('</svg>')
    (ROOT / "preview.svg").write_text("\n".join(sheet) + "\n", encoding="utf-8")


def write_review_png():
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        return False
    ink, panel, bg, rim = (238, 232, 220), (28, 28, 37), (17, 18, 24), (142, 53, 70)
    names = MODELS + ["EmptyHand"]

    def render(polygons, px, ss=4):
        im = Image.new("RGB", (px * ss, px * ss), panel)
        d = ImageDraw.Draw(im)
        for poly in polygons:
            d.polygon([(x * px * ss / 100, y * px * ss / 100) for x, y in poly], fill=ink)
        return im.resize((px, px), Image.Resampling.LANCZOS)

    big, small, cols = 256, 48, 5
    rows = (len(names) + cols - 1) // cols
    W = cols * (big + 12) + 12
    H = rows * (big + 30) + 12 + 2 * (small + 40) + 20
    sheet = Image.new("RGB", (W, H), bg)
    d = ImageDraw.Draw(sheet)
    for i, name in enumerate(names):
        x, y = 12 + (i % cols) * (big + 12), 12 + (i // cols) * (big + 30)
        sheet.paste(render(MODEL_ICONS[name], big), (x, y))
        d.rectangle((x, y, x + big - 1, y + big - 1), outline=rim)
        d.text((x + 6, y + big + 6), DISPLAY.get(name, name), fill=(233, 231, 226))
    # 48 px strip: roughly the in-headset size of one slot icon.
    y0 = 12 + rows * (big + 30) + 10
    d.text((12, y0), "48 px (approx. in-HMD slot size), all enum entries incl. generic fallbacks", fill=(201, 196, 187))
    for i, name in enumerate(ORDER):
        x = 12 + (i % 9) * (small + 50)
        y = y0 + 18 + (i // 9) * (small + 22)
        sheet.paste(render(shape(name), small), (x, y))
        d.text((x, y + small + 2), name[:10], fill=(150, 146, 140))
    sheet.save(ROOT / "revision-preview.png")
    return True


def generate():
    stats = validate()
    write_header()
    write_svgs()
    png = write_review_png()
    return stats, png


if __name__ == "__main__":
    stats, png = generate()
    for name in ORDER:
        p, t = stats[name]
        print(f"{name:13s} polygons={p:2d} triangles={t:2d}" + (f"  (alias of {ALIAS[name]})" if name in ALIAS else ""))
    print(f"Generated {len(ORDER)} icons; bounds/convexity/area/budget PASS" + ("; review PNG written" if png else ""))
