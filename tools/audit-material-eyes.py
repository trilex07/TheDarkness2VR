"""Read private native shader blobs/captures; emit identities, never game assets.

Triage is deliberately limited to c8 -> tangent TEXCOORD1 -> PS v2 normalisation.
The generated allowlist still requires full bytecode digests, an observed VS/PS
pair, and runtime raw-eye/WVP ownership checks. This is not full-game coverage.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
from disassemble_shader import disassemble


def identity(path):
    data = path.read_bytes()
    h = 2166136261
    for byte in data:
        h = ((h ^ byte) * 16777619) & 0xffffffff
    return dict(hash=f'{h:08X}', size=len(data), sha256=hashlib.sha256(data).hexdigest())


def tangent_eye(text):
    if '    vs_3_0' not in text:
        return False
    code = text.split('    vs_3_0', 1)[1]
    sub = re.search(r'add (r\d+)\.xyz, (?:c8, -([^\n]+)|-([^,]+), c8)', code)
    if not sub or 'dcl_texcoord1 o3' not in code or 'def c8,' in code:
        return False
    eye = sub[1]
    outputs = [re.search(r'dp3 o3\.' + c + r', ' + eye + r', r\d+', code) for c in 'xyz']
    if not all(outputs) or min(m.start() for m in outputs) < sub.end():
        return False
    # Reject register reuse before the final tangent-eye component is emitted.
    span = code[sub.end():max(m.start() for m in outputs)]
    for dest in re.findall(r'^\s*\w+\s+(' + eye + r'(?:\.[xyzw]+)?),', span, re.M):
        if '.' not in dest or any(c in dest.split('.')[1] for c in 'xyz'):
            return False
    return all(token in code for token in ('c0', 'c1', 'c2', 'c3'))


def consumer(text):
    return bool(re.search(r'dcl_texcoord1(?:_pp)? v2(?:\b|\.)', text) and
                re.search(r'nrm(?:_pp)? r\d+\.xyz, v2\b', text) and
                ('Shine' in text or 'ReflectionMap' in text))


def observed(paths):
    pairs = set()
    for path in sorted(paths):
        text = path.read_text(errors='replace')
        vertices = {}
        for match in re.finditer(r'\{"kind":"(draw|draw_ps)".*?\}', text, re.S):
            row = json.loads(match.group())
            key = row['eye'], row['draw']
            if row['kind'] == 'draw':
                vertices[key] = f"{row['shader_hash']:08X}"
            elif key in vertices:
                pairs.add((vertices[key], f"{row['shader_hash']:08X}"))
    return pairs


def emit_header(path, vertices, pixels, pairs):
    lines = ['#pragma once', '// Native identities only; generated by tools/audit-material-eyes.py.',
             '#include <cstdint>', '#include <cstddef>', 'namespace d2vr_material_eyes {',
             'struct Entry {uint32_t hash;size_t bytes;const char* sha;};']
    for name, entries in [('Vertices', vertices), ('Pixels', pixels)]:
        lines.append(f'inline constexpr Entry k{name}[]={{')
        for row in sorted(entries, key=lambda r: r['hash']):
            lines.append(f'    {{0x{row["hash"]}u,{row["size"]},"{row["sha256"]}"}},')
        lines.append('};')
    lines.append('inline constexpr uint64_t kPairs[]={')
    lines.extend(f'    0x{v}{p}ull,' for v, p in sorted(pairs))
    lines.extend(['};',
        'template<size_t N,class Verify> bool Admit(const Entry (&entries)[N],uint32_t hash,size_t bytes,Verify&& verify) {',
        '    size_t lo=0,hi=N;while(lo<hi){size_t mid=lo+(hi-lo)/2;if(entries[mid].hash<hash)lo=mid+1;else hi=mid;}',
        '    return lo<N && entries[lo].hash==hash && entries[lo].bytes==bytes && verify(entries[lo].sha);',
        '}',
        'inline bool Pair(uint32_t vs,uint32_t ps) {',
        '    const uint64_t key=(uint64_t(vs)<<32)|ps;size_t lo=0,hi=sizeof(kPairs)/sizeof(*kPairs);',
        '    while(lo<hi){size_t mid=lo+(hi-lo)/2;if(kPairs[mid]<key)lo=mid+1;else hi=mid;}',
        '    return lo<sizeof(kPairs)/sizeof(*kPairs) && kPairs[lo]==key;',
        '}', '}'])
    path.write_text('\n'.join(lines) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--shaders', type=Path, required=True)
    ap.add_argument('--captures', type=Path, nargs='+', required=True)
    ap.add_argument('--report', type=Path, required=True)
    ap.add_argument('--header', type=Path)
    args = ap.parse_args()
    entries = {}
    for path in sorted(args.shaders.glob('*.bin')):
        row = identity(path)
        stage = path.name[:2]
        if stage not in ('vs', 'ps') or path.stem[3:] != row['hash']:
            raise ValueError(f'Unexpected shader identity: {path}')
        text = disassemble(path)
        row.update(stage=stage, tangent_eye=stage == 'vs' and tangent_eye(text),
                   eye_consumer=stage == 'ps' and consumer(text))
        entries[stage, row['hash']] = row
    paths = set()
    for root in args.captures:
        paths.update(root.glob('**/manifest.jsonl'))
    all_pairs = observed(paths)
    pairs = {(v, p) for v, p in all_pairs if entries.get(('vs', v), {}).get('tangent_eye') and
             entries.get(('ps', p), {}).get('eye_consumer')}
    vs = [entries['vs', v] for v in sorted({v for v, p in pairs})]
    ps = [entries['ps', p] for p in sorted({p for v, p in pairs})]
    report = dict(shader_count=len(entries), manifests=len(paths),
                  tangent_eye_vertices=sum(r['tangent_eye'] for r in entries.values()),
                  admitted_vertices=vs, admitted_pixels=ps, pairs=sorted(pairs),
                  excluded_observed_pairs=sorted(all_pairs-pairs),
                  limit='Previously collected shader bytecode and draw identities, not full-game or headset coverage')
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2))
    if args.header:
        emit_header(args.header, vs, ps, pairs)
    print(f'{len(entries)} shaders, {len(paths)} manifests: {len(vs)} VS, {len(ps)} PS, {len(pairs)} eligible pairs')


if __name__ == '__main__':
    main()
