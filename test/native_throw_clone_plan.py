"""Pinned native release-event relocation metadata; never export game bytes."""
import argparse
import hashlib
import json
from pathlib import Path

import pefile
import native_view_clone_plan as cfg

FUNCTIONS = [(0xD23220, 0x775), (0x878930, 0x15BD)]
DIGESTS = ["a6164a3b384bbbfbc787149ad3c9814b99d792a497ba36044a9eda5a9e14d656",
           "ed78b0ce308d0a54efca74dae49f1aef8de97db49b6c1bea45a5526a903a067e"]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--exe", required=True, type=Path)
    parser.add_argument("--header", type=Path)
    parser.add_argument("--check-header", type=Path)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    assert hashlib.sha256(args.exe.read_bytes()).hexdigest() == cfg.EXE_SHA
    pe = pefile.PE(str(args.exe))
    assert pe.FILE_HEADER.Machine == 0x14C and pe.OPTIONAL_HEADER.ImageBase == 0x400000
    cfg.FUNCTIONS = FUNCTIONS
    blocks = [cfg.audit(pe, start, size) for start, size in FUNCTIONS]
    assert [block["sha256"] for block in blocks] == DIGESTS
    assert [len(block["calls"]) for block in blocks] == [41, 139]
    assert (0xD23972-0xD23220, 0x878930) in blocks[0]["calls"]
    assert (0x879C88-0x878930, 0x6DA050) in blocks[1]["calls"]
    read = lambda va, size: pe.get_data(va-0x400000, size)
    assert int.from_bytes(read(0x1004FE8+0x74, 4), "little") == 0xD23220
    for index in range(35):
        target = int.from_bytes(read(0x1004FE8+4*index, 4), "little")
        assert any(s.Characteristics & 0x20000000 and
                   s.VirtualAddress <= target-0x400000 < s.VirtualAddress+s.Misc_VirtualSize for s in pe.sections)
    # Pin the complete table/header, retaining native RTTI and all other slots.
    table_sha = hashlib.sha256(read(0x1004FE4, 36*4)).hexdigest()
    text = ["#pragma once", "// Generated by test/native_throw_clone_plan.py. Relocation metadata only.",
            '#include "native_view_code_clone.h"', "namespace d2vr_native_clone {",
            "inline const Block throwBlocks[]={"]
    for block in blocks:
        text.append('    {reinterpret_cast<void*>(0x%X),0x%X,"%s"},' %
                    (block["address"], block["size"], block["sha256"]))
    text.extend(["};", "inline const Call throwCalls[]={"])
    for index, block in enumerate(blocks):
        for offset, target in block["calls"]:
            text.append("    {%d,0x%X,0x%X}," % (index, offset, target))
    text.extend(["};", 'inline constexpr unsigned throwTableCount=35;',
                 'inline const char* throwTableDigest="%s";' % table_sha, "}", ""])
    header = "\n".join(text)
    if args.check_header:
        assert args.check_header.read_text(encoding="utf-8-sig") == header
    if args.header:
        args.header.write_text(header, encoding="utf-8")
    if args.report:
        args.report.write_text(json.dumps({"status": "STATIC_CFG_PASS_NOT_RUNTIME",
            "exe_sha256": cfg.EXE_SHA, "blocks": blocks, "table_sha256": table_sha,
            "limitations": "Copied call return addresses move; native callee compatibility requires runtime evidence."}, indent=2)+"\n")
    print("PASS pinned throw CFG: 2 blocks,180 rel32 calls,35 table methods/header; no escaping/computed jumps, local SEH or code pointers")


if __name__ == "__main__":
    main()
