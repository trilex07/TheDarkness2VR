"""Audit native weapon entry contracts; emit only offsets/digests, never bytes."""
import argparse
import hashlib
from pathlib import Path

import capstone as cs
import pefile
import native_view_clone_plan as cfg

MODEL, MODEL_SIZE, CUT = 0xAD9240, 0x39A, 0x267
FIRE, FIRE_SIZE = 0xCFBBA0, 0x227


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--exe", required=True, type=Path)
    parser.add_argument("--header", type=Path)
    parser.add_argument("--check-header", type=Path)
    parser.add_argument("--fire-fixture-body", type=Path)
    args = parser.parse_args()
    assert hashlib.sha256(args.exe.read_bytes()).hexdigest() == cfg.EXE_SHA
    pe = pefile.PE(str(args.exe))
    read = lambda va, n: pe.get_data(va - 0x400000, n)
    cfg.FUNCTIONS = [(MODEL, MODEL_SIZE), (FIRE, FIRE_SIZE)]
    model = cfg.audit(pe, MODEL, MODEL_SIZE)
    fire = cfg.audit(pe, FIRE, FIRE_SIZE)
    assert model["sha256"] == "bf9a831e25edeae337594147740166dc2462b7b7109a18ebf4092ca0be984dda"
    assert fire["sha256"] == "b6aa8249b730a8a3d571fe611db42417d66c151f20b7984c545675a7ab4c910a"
    decoder = cs.Cs(cs.CS_ARCH_X86, cs.CS_MODE_32)
    decoder.detail = True
    for contract, pop in [(model, 4), (fire, 20)]:
        for address in contract["returns"]:
            instruction = next(decoder.disasm(read(address, 3), address))
            assert instruction.mnemonic == "ret" and instruction.operands[0].imm == pop
    prefix = list(decoder.disasm(read(MODEL, CUT), MODEL))
    assert prefix[-1].address == 0xAD94A2 and prefix[-1].size == 5
    assert prefix[-1].address + prefix[-1].size == MODEL + CUT
    calls = [(i.address - MODEL, i.operands[0].imm) for i in prefix if i.group(cs.CS_GRP_CALL)]
    assert all(i.operands[0].type == cs.x86.X86_OP_IMM for i in prefix if i.group(cs.CS_GRP_CALL))
    assert set(target for _, target in calls) == {0x8B9150, 0xC02F50, 0x4CBE70, 0x481F50}
    exits = []
    starts = {i.address for i in prefix}
    for i in prefix:
        if i.group(cs.CS_GRP_JUMP):
            target = i.operands[0].imm
            if MODEL <= target < MODEL + CUT:
                assert target in starts
            else:
                assert i.size == 6 and i.bytes[0] == 0x0F and i.bytes[1] & 0xF0 == 0x80
                exits.append((i.address - MODEL, target))
    assert exits == [(0x27, 0xAD95C3), (0x36, 0xAD95C3)]
    assert (0x262, 0x481F50) in calls
    # The copied prefix's callees read arguments, not its moved return address.
    # Nested calls remain native, including renderer bone lookup and arithmetic.
    helpers = [(0x8B9150, 0x93), (0xC02F50, 0x138), (0x4CBE70, 0x1B4), (0x481F50, 0)]
    # Compare's full boundary is independently recovered from its native RET.
    for i in decoder.disasm(read(0x481F50, 1024), 0x481F50):
        if i.group(cs.CS_GRP_RET):
            helpers[-1] = (0x481F50, i.address + i.size - 0x481F50)
            break
    assert helpers[-1][1]
    for address, size in helpers + [(FIRE, FIRE_SIZE),(0xC47570,0x35D)]:
        for i in decoder.disasm(read(address, size), address):
            for operand in i.operands:
                if operand.type == cs.x86.X86_OP_MEM and operand.mem.base == cs.x86.X86_REG_EBP:
                    assert operand.mem.disp != 4, f"Return-address read at {i.address:x}"
    text = ["#pragma once", "// Generated by test/native_weapon_prefix_plan.py. No native bytes.",
            '#include "native_view_code_clone.h"', "namespace d2vr_native_clone {",
            'inline const Block weaponModelBlock{reinterpret_cast<void*>(0xAD9240),0x39A,"%s"};' % model["sha256"],
            "inline const Call weaponModelCalls[]={"]
    text.extend("    {0,0x%X,0x%X}," % c for c in calls)
    text.extend(["};", "inline const PrefixExit weaponModelExits[]={{0x27,0xAD95C3},{0x36,0xAD95C3}};",
                 "inline const Prefix weaponModelPrefix{0x267,weaponModelExits,2};",
                 "inline const Block weaponHelpers[]={"])
    text.extend('    {reinterpret_cast<void*>(0x%X),0x%X,"%s"},' %
                (address, size, hashlib.sha256(read(address, size)).hexdigest()) for address, size in helpers)
    assert (0xCFBD60-FIRE,0xC47570) in fire['calls']
    assert sum(target==0xC47570 for _,target in fire['calls'])==1
    consumer=read(0xC47570,0x35D)
    assert consumer[-3:]==bytes.fromhex('c21400')
    text.extend(["};", 'inline const Block weaponFireBlock{reinterpret_cast<void*>(0xCFBBA0),0x227,"%s"};' % fire["sha256"],
                 "inline const Call weaponFireCalls[]={"])
    text.extend("    {0,0x%X,0x%X}," % c for c in fire['calls'])
    text.extend(["};",'inline const Block weaponShotConsumer{reinterpret_cast<void*>(0xC47570),0x35D,"%s"};' % hashlib.sha256(consumer).hexdigest()])
    for name, table, count, slot, entry in [("weaponModel", 0xFD6BC0, 131, 0xF0, MODEL),
                                           ("weaponFire", 0x1010AE0, 33, 0x64, FIRE)]:
        assert int.from_bytes(read(table + slot, 4), "little") == entry
        assert int.from_bytes(read(table + count * 4, 4), "little") == 0
        for index in range(count):
            target = int.from_bytes(read(table + index * 4, 4), "little")
            assert any(s.Characteristics & 0x20000000 and s.VirtualAddress <= target - 0x400000 <
                       s.VirtualAddress + s.Misc_VirtualSize for s in pe.sections)
        digest = hashlib.sha256(read(table - 4, (count + 1) * 4)).hexdigest()
        text.extend([f"inline constexpr unsigned {name}TableCount={count};",
                     f'inline const char* {name}TableDigest="{digest}";'])
    text.extend(["}", ""])
    result = "\n".join(text)
    if args.check_header:
        assert args.check_header.read_text(encoding="utf-8-sig") == result
    if args.header:
        args.header.write_text(result, encoding="utf-8")
    if args.fire_fixture_body:
        destination=args.fire_fixture_body.resolve()
        assert not destination.is_relative_to(Path(__file__).resolve().parents[1]), 'Keep original bytes outside Git'
        destination.write_bytes(read(FIRE,FIRE_SIZE))
    print(f"PASS native weapon CFG: {len(calls)} model prefix calls,2 native early exits,original AD94A7 continuation;{len(fire['calls'])} fire calls, final CFBD60->C47570;131+33 tables;ret20; not runtime proof")


if __name__ == "__main__":
    main()
